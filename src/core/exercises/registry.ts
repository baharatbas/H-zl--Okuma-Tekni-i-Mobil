/** İpuçları ayrı dosyada tutulur; her egzersiz metadatasına eklenir. */
export const EXERCISES: Record<ExerciseKey, ExerciseMeta> = Object.fromEntries(
  (Object.keys(RAW_EXERCISES) as ExerciseKey[]).map((k) => [k, { ...RAW_EXERCISES[k], tip: EXERCISE_TIPS[k] }]),
) as Record<ExerciseKey, ExerciseMeta>;

export const EXERCISE_KEYS = Object.keys(EXERCISES) as ExerciseKey[];

export function isExerciseKey(value: string): value is ExerciseKey {
  return value in EXERCISES;
}
